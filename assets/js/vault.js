// Cuberoot vault — all encryption for the documentation library.
// Runs entirely in the browser (Web Crypto API). Nothing here talks to a server.
//
// Scheme (version 1)
// - Each app has its own random 256-bit AES-GCM key.
// - Every document is encrypted with its app key. The file on GitHub is:
//     1 byte version (0x01) | 12 byte random IV | AES-GCM ciphertext + tag
//   The additional data binds the ciphertext to its place: "doc:<slug>/<id>".
// - Each app has an encrypted index (vault/<slug>/index.json) listing its documents.
// - Each reader has a random 256-bit reader key. It is wrapped with a key derived
//   from the reader's passphrase (PBKDF2-SHA-256, 600,000 iterations, random salt).
//   A separate "grant", encrypted with the reader key, holds the keys of the apps
//   that reader may read. The admin keeps every reader key inside the admin state,
//   so access can be changed or keys rotated without knowing anyone's passphrase.
// - The admin state (vault/admin.json) is encrypted with a key derived from the
//   admin passphrase the same way.

export const ITERATIONS = 600000;
const enc = new TextEncoder();
const dec = new TextDecoder();
const subtle = globalThis.crypto.subtle;

// ---------- encoding helpers ----------
export function toB64(bytes) {
  const u8 = bytes instanceof Uint8Array ? bytes : new Uint8Array(bytes);
  let s = '';
  const CH = 0x8000;
  for (let i = 0; i < u8.length; i += CH) s += String.fromCharCode.apply(null, u8.subarray(i, i + CH));
  return btoa(s);
}
export function fromB64(b64) {
  const s = atob(b64);
  const u8 = new Uint8Array(s.length);
  for (let i = 0; i < s.length; i++) u8[i] = s.charCodeAt(i);
  return u8;
}
export function randomBytes(n) {
  const u8 = new Uint8Array(n);
  for (let i = 0; i < n; i += 65536) globalThis.crypto.getRandomValues(u8.subarray(i, Math.min(n, i + 65536)));
  return u8;
}
export function randomId() {
  return Array.from(randomBytes(16), b => b.toString(16).padStart(2, '0')).join('');
}
async function sha256Hex(text) {
  const h = new Uint8Array(await subtle.digest('SHA-256', enc.encode(text)));
  return Array.from(h, b => b.toString(16).padStart(2, '0')).join('');
}

// ---------- keys ----------
export function newKeyB64() { return toB64(randomBytes(32)); }

export async function importKey(rawB64) {
  return subtle.importKey('raw', fromB64(rawB64), { name: 'AES-GCM' }, false, ['encrypt', 'decrypt']);
}

export async function deriveKey(passphrase, saltB64, iterations = ITERATIONS) {
  const base = await subtle.importKey('raw', enc.encode(passphrase), 'PBKDF2', false, ['deriveKey']);
  return subtle.deriveKey(
    { name: 'PBKDF2', hash: 'SHA-256', salt: fromB64(saltB64), iterations },
    base, { name: 'AES-GCM', length: 256 }, false, ['encrypt', 'decrypt']);
}

async function asKey(k) { return typeof k === 'string' ? importKey(k) : k; }

// ---------- raw encryption ----------
export async function encryptBytes(key, bytes, aad) {
  const k = await asKey(key);
  const iv = randomBytes(12);
  const ct = new Uint8Array(await subtle.encrypt({ name: 'AES-GCM', iv, additionalData: enc.encode(aad) }, k, bytes));
  const out = new Uint8Array(1 + 12 + ct.length);
  out[0] = 1; out.set(iv, 1); out.set(ct, 13);
  return out;
}

export async function decryptBytes(key, data, aad) {
  const k = await asKey(key);
  const u8 = data instanceof Uint8Array ? data : new Uint8Array(data);
  if (u8[0] !== 1) throw new Error('Unknown file format');
  const iv = u8.subarray(1, 13);
  const pt = await subtle.decrypt({ name: 'AES-GCM', iv, additionalData: enc.encode(aad) }, k, u8.subarray(13));
  return new Uint8Array(pt);
}

export async function encryptJSON(key, obj, aad) {
  return { v: 1, data: toB64(await encryptBytes(key, enc.encode(JSON.stringify(obj)), aad)) };
}
export async function decryptJSON(key, box, aad) {
  if (!box || box.v !== 1) throw new Error('Unknown format');
  return JSON.parse(dec.decode(await decryptBytes(key, fromB64(box.data), aad)));
}

// ---------- passphrases ----------
// Reader passphrases are generated by the admin page: 5 groups of 4 characters
// from an alphabet without look-alike characters (about 99 bits).
const ALPHABET = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
export function generatePassphrase() {
  const groups = [];
  for (let g = 0; g < 5; g++) {
    let s = '';
    while (s.length < 4) {
      const b = randomBytes(1)[0];
      if (b < 256 - (256 % ALPHABET.length)) s += ALPHABET[b % ALPHABET.length];
    }
    groups.push(s);
  }
  return groups.join('-');
}
export function normalizePassphrase(p, norm) {
  if (norm === 'code') return String(p).toUpperCase().replace(/[^A-Z0-9]/g, '');
  return String(p).normalize('NFC');
}
export function normalizeEmail(e) { return String(e).trim().toLowerCase(); }
export async function readerId(email) { return sha256Hex('cuberoot-reader:v1:' + normalizeEmail(email)); }

// ---------- readers ----------
// A reader record kept (encrypted) in the admin state:
//   { id, name, email, scope: 'all' | [slugs], rkey, norm, created }
// The public entry written to vault/readers.json:
//   { id, norm, kdf: {salt, iter}, wrap, grant }

export async function wrapReaderKey(record, passphrase) {
  const salt = toB64(randomBytes(16));
  const kek = await deriveKey(normalizePassphrase(passphrase, record.norm), salt);
  const wrap = await encryptJSON(kek, { rkey: record.rkey }, 'reader-wrap:' + record.id);
  return { salt, iter: ITERATIONS, wrap };
}

export function appsForScope(scope, apps) {
  const slugs = Object.keys(apps);
  const allowed = scope === 'all' ? slugs : slugs.filter(s => scope.includes(s));
  return allowed.map(s => ({ slug: s, name: apps[s].name, key: apps[s].key }));
}

export async function buildReaderEntry(record, lock, apps) {
  const grant = await encryptJSON(record.rkey,
    { name: record.name, email: record.email, apps: appsForScope(record.scope, apps) },
    'reader-grant:' + record.id);
  return { id: record.id, norm: record.norm, kdf: { salt: lock.salt, iter: lock.iter }, wrap: lock.wrap, grant };
}

// Sign in: returns { name, email, apps: [{slug, name, key}] } or throws.
export async function openReader(readersFile, email, passphrase) {
  const id = await readerId(email);
  const entry = (readersFile.readers || []).find(r => r.id === id);
  if (!entry) throw new Error('no-match');
  const kek = await deriveKey(normalizePassphrase(passphrase, entry.norm), entry.kdf.salt, entry.kdf.iter);
  let rkey;
  try { rkey = (await decryptJSON(kek, entry.wrap, 'reader-wrap:' + id)).rkey; }
  catch (e) { throw new Error('no-match'); }
  return decryptJSON(rkey, entry.grant, 'reader-grant:' + id);
}

// ---------- admin state ----------
export async function sealAdmin(state, passphrase, saltB64) {
  const salt = saltB64 || toB64(randomBytes(16));
  const kek = await deriveKey(normalizePassphrase(passphrase, 'text'), salt);
  return { file: { v: 1, kdf: { salt, iter: ITERATIONS }, state: await encryptJSON(kek, state, 'admin-state') }, kek };
}
export async function openAdmin(file, passphrase) {
  const kek = await deriveKey(normalizePassphrase(passphrase, 'text'), file.kdf.salt, file.kdf.iter);
  try { return { state: await decryptJSON(kek, file.state, 'admin-state'), kek }; }
  catch (e) { throw new Error('wrong-passphrase'); }
}
export async function resealAdmin(file, kek, state) {
  return { v: 1, kdf: file.kdf, state: await encryptJSON(kek, state, 'admin-state') };
}

// ---------- documents ----------
export const docPath = (slug, id) => `vault/${slug}/${id}.bin`;
export const indexPath = slug => `vault/${slug}/index.json`;
export const encryptDoc = (key, slug, id, bytes) => encryptBytes(key, bytes, `doc:${slug}/${id}`);
export const decryptDoc = (key, slug, id, bytes) => decryptBytes(key, bytes, `doc:${slug}/${id}`);
export const encryptIndex = (key, slug, index) => encryptJSON(key, index, `index:${slug}`);
export const decryptIndex = (key, slug, box) => decryptJSON(key, box, `index:${slug}`);

// ---------- names ----------
export function slugify(name) {
  return String(name).toLowerCase().normalize('NFKD').replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 48) || 'app';
}

// "Expense-Ledger-Deployment-Guide.pdf" in app "Expense Ledger" -> "Deployment Guide"
export function titleFromFilename(filename, appName) {
  let base = String(filename).replace(/\.[^.]+$/, '');
  base = base.replace(/[_\-.]+/g, ' ').replace(/\s+/g, ' ').trim();
  if (appName) {
    const prefix = String(appName).replace(/[_\-.]+/g, ' ').trim();
    if (prefix && base.toLowerCase().startsWith(prefix.toLowerCase() + ' ')) base = base.slice(prefix.length).trim();
  }
  if (base && base === base.toUpperCase() && /[A-Z]/.test(base)) {
    base = base.toLowerCase().replace(/\b\w/g, c => c.toUpperCase());
  }
  return base || String(filename);
}

const MIME = { pdf: 'application/pdf', md: 'text/plain; charset=utf-8', markdown: 'text/plain; charset=utf-8',
  txt: 'text/plain; charset=utf-8', html: 'text/plain; charset=utf-8', png: 'image/png', jpg: 'image/jpeg',
  jpeg: 'image/jpeg', docx: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
  xlsx: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', zip: 'application/zip' };
export function fileKind(filename) {
  const m = /\.([A-Za-z0-9]+)$/.exec(filename);
  const ext = m ? m[1].toLowerCase() : '';
  return { ext, label: (ext || 'FILE').toUpperCase().slice(0, 4), mime: MIME[ext] || 'application/octet-stream' };
}
